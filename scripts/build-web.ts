/**
 * Bundles the web client (web/) and writes it into src/chat/web-assets.generated.ts, so the chat Lambda
 * serves it from memory with no extra hosting service. Run before typecheck, tests and `sam build`
 * (the npm pre-scripts do this automatically for typecheck and test).
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const bundle = await build({
  entryPoints: ['web/src/main.ts'],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  minify: true,
  write: false,
  legalComments: 'none',
});
const appJs = bundle.outputFiles[0]!.text;

const assets = {
  '/index.html': { contentType: 'text/html; charset=utf-8', body: readFileSync('web/index.html', 'utf8') },
  '/styles.css': { contentType: 'text/css; charset=utf-8', body: readFileSync('web/styles.css', 'utf8') },
  '/app.js': { contentType: 'text/javascript; charset=utf-8', body: appJs },
};

writeFileSync(
  'src/chat/web-assets.generated.ts',
  `// Generated by scripts/build-web.ts from web/. Do not edit; run \`npm run build:web\`.\n` +
    `import type { StaticAsset } from './app.js';\n\n` +
    `export const WEB_ASSETS: Record<string, StaticAsset> = ${JSON.stringify(assets, null, 2)};\n`,
);
console.log(`Web client built: app.js ${(appJs.length / 1024).toFixed(1)} KiB`);
